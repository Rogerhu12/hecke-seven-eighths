#!/usr/bin/env python3
"""Pack the project's precompiled Lake artifacts into a GitHub release.

The release is consumed by `.github/actions/restore-lake-cache`.  It holds the
Lake build outputs of every project library except the ones listed in
`--exclude` (by default the fast-moving `HeckeSkeleton` and the branch-local
`ThetaGlobal`, plus the two one-file challenge libraries), together with the
outputs of the two non-Mathlib packages `vendor/class-field-theory` and
`TauCeti`.  Mathlib and its dependencies are *not* packed: CI gets them from
the official Mathlib cache (`lake exe cache get`).

Only the files Lake 4.35 needs to treat a module as up to date are packed:

  lib/lean/**.trace                          saved input hash (`depHash`)
  lib/lean/**.olean .ilean                   checked by `checkArtifactsExist`
  lib/lean/**.olean.server .olean.private    (module-system modules only)
  lib/lean/**.ir .ir.sig                     (module-system modules only)
  ir/**.c                                    also checked by `checkArtifactsExist`
  every `<artifact>.hash`                    trusted cached content hashes

`ir/**.setup.json` (about 90% of the bytes of a local build) is regenerated by
Lake before each compilation and is never read for an up-to-date check, so it
is skipped.  Modules whose `.lean` source in the working tree differs from
`--ref` (and everything importing them) are skipped too, since CI would
rebuild them anyway.  See `cloud_tasks/README.md`, section "CI 预编译缓存".

Usage (from the repository root, after a complete `lake build` of the
libraries on the commit the cache is meant for):

    python3 scripts/build_lake_cache.py --out /tmp/lake-cache
    python3 scripts/build_lake_cache.py --out /tmp/lake-cache --upload

The script only reads the build directories.  With `--upload` it runs
`gh release create lake-cache-<short sha> --draft` and uploads the parts;
publish the draft after the `lake-cache-test` workflow has passed on it.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
import tarfile
import threading
import time
from pathlib import Path

BUILD_ROOTS = [
    ".lake/build",
    "vendor/class-field-theory/.lake/build",
    ".lake/packages/TauCeti/.lake/build",
]

LIB_SUFFIXES = (
    ".trace",
    ".olean",
    ".olean.hash",
    ".ilean",
    ".ilean.hash",
    ".olean.server",
    ".olean.server.hash",
    ".olean.private",
    ".olean.private.hash",
    ".ir",
    ".ir.hash",
    ".ir.sig",
    ".ir.sig.hash",
)
IR_SUFFIXES = (".c", ".c.hash")

DEFAULT_EXCLUDE = [
    "HeckeSkeleton",
    "ThetaGlobal",
    "DedekindZetaChallenge",
    "DedekindZetaSolution",
]

PART_PREFIX = "lake-cache.tar.zst.part-"


def module_of(rel: str) -> str:
    """`DedekindZetaZeroFree/Theta/Foo.olean.hash` -> `DedekindZetaZeroFree.Theta.Foo`."""
    name = rel.split("/")[-1]
    stem = name.split(".", 1)[0]
    return ".".join(rel.split("/")[:-1] + [stem])


def excluded(module: str, prefixes: list[str]) -> bool:
    return any(module == p or module.startswith(p + ".") for p in prefixes)


TRANSITIVE = " transitive imports (legacy)"


def read_traces(repo: Path) -> dict[str, tuple[str | None, list[str]]]:
    """module -> (source path relative to the repo, direct imports), from the `.trace` files."""
    out: dict[str, tuple[str | None, list[str]]] = {}
    for root in BUILD_ROOTS:
        top = repo / root / "lib/lean"
        for dirpath, _, filenames in os.walk(top):
            for f in filenames:
                if not f.endswith(".trace"):
                    continue
                rel = os.path.relpath(os.path.join(dirpath, f), top)[: -len(".trace")]
                mod = rel.replace(os.sep, ".")
                try:
                    trace = json.loads(Path(dirpath, f).read_text(encoding="utf-8"))
                except (OSError, ValueError):
                    continue
                src, imports = None, []
                for entry in trace.get("inputs", []):
                    cap, val = entry[0], entry[1]
                    if cap == "deps":
                        for sub in val:
                            if sub[0] == "imports":
                                imports += [e[0][: -len(TRANSITIVE)] for e in sub[1]
                                            if isinstance(e[0], str) and e[0].endswith(TRANSITIVE)]
                    elif isinstance(cap, str) and cap.endswith(".lean") and isinstance(val, str):
                        try:
                            src = Path(cap).resolve().relative_to(repo).as_posix()
                        except ValueError:
                            src = None
                out[mod] = (src, imports)
    return out


def stale_modules(repo: Path, ref: str) -> tuple[list[str], set[str]]:
    """Modules whose sources in the working tree differ from `ref`, plus everything importing them.

    Their artifacts were compiled from sources CI will not see, so Lake would rebuild them
    anyway; packing them would only waste space and make the manifest misleading.
    """
    changed = set(git(repo, "diff", "--name-only", ref, "--", "*.lean").splitlines())
    changed |= set(git(repo, "ls-files", "--others", "--exclude-standard", "--", "*.lean").splitlines())
    traces = read_traces(repo)
    roots = sorted(m for m, (src, _) in traces.items() if src in changed)
    rdeps: dict[str, list[str]] = {}
    for m, (_, imports) in traces.items():
        for i in imports:
            rdeps.setdefault(i, []).append(m)
    cone, todo = set(roots), list(roots)
    while todo:
        for user in rdeps.get(todo.pop(), []):
            if user not in cone:
                cone.add(user)
                todo.append(user)
    return roots, cone


def collect(repo: Path, exclude: list[str], skip: set[str] = frozenset()) -> tuple[list[str], dict]:
    files: list[str] = []
    stats: dict[str, dict[str, int]] = {}
    for root in BUILD_ROOTS:
        base = repo / root
        if not base.is_dir():
            raise SystemExit(f"missing build directory: {base}")
        n = size = mods = 0
        for sub, suffixes in (("lib/lean", LIB_SUFFIXES), ("ir", IR_SUFFIXES)):
            top = base / sub
            if not top.is_dir():
                continue
            for dirpath, dirnames, filenames in os.walk(top):
                dirnames.sort()
                reldir = os.path.relpath(dirpath, top).replace(os.sep, "/")
                reldir = "" if reldir == "." else reldir + "/"
                for f in sorted(filenames):
                    if not f.endswith(suffixes):
                        continue
                    rel = reldir + f
                    mod = module_of(rel)
                    if mod in skip or excluded(mod, exclude):
                        continue
                    path = f"{root}/{sub}/{rel}"
                    files.append(path)
                    n += 1
                    size += (repo / path).stat().st_size
                    if f.endswith(".trace"):
                        mods += 1
        stats[root] = {"files": n, "bytes": size, "modules": mods}
    return files, stats


def git(repo: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(repo), *args], check=True, capture_output=True, text=True
    ).stdout.strip()


def pack(repo: Path, files: list[str], out: Path, part_size: int, level: int) -> list[dict]:
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob(PART_PREFIX + "*"):
        old.unlink()
    zstd = subprocess.Popen(
        ["zstd", "-q", f"-{level}", "-T0", "-c"],
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
    )
    parts: list[dict] = []

    def sink() -> None:
        idx, written, h, fh = 0, 0, None, None
        while True:
            chunk = zstd.stdout.read(1 << 20)
            if not chunk:
                break
            while chunk:
                if fh is None:
                    name = f"{PART_PREFIX}{idx:03d}"
                    fh = open(out / name, "wb")
                    h = hashlib.sha256()
                    parts.append({"name": name})
                take = chunk[: part_size - written]
                fh.write(take)
                h.update(take)
                written += len(take)
                chunk = chunk[len(take):]
                if written >= part_size:
                    fh.close()
                    parts[-1].update(bytes=written, sha256=h.hexdigest())
                    idx, written, fh = idx + 1, 0, None
        if fh is not None:
            fh.close()
            parts[-1].update(bytes=written, sha256=h.hexdigest())

    t = threading.Thread(target=sink)
    t.start()
    with tarfile.open(fileobj=zstd.stdin, mode="w|", format=tarfile.PAX_FORMAT) as tar:
        for i, rel in enumerate(files):
            info = tar.gettarinfo(str(repo / rel), arcname=rel)
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            info.mode = 0o644
            with open(repo / rel, "rb") as fh:
                tar.addfile(info, fh)
            if i % 2000 == 0:
                print(f"  packed {i}/{len(files)}", flush=True)
    zstd.stdin.close()
    t.join()
    if zstd.wait() != 0:
        raise SystemExit("zstd failed")
    return parts


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", type=Path, default=Path.cwd())
    ap.add_argument("--out", type=Path, required=True, help="directory for the parts")
    ap.add_argument("--exclude", nargs="*", default=DEFAULT_EXCLUDE,
                    help="module-name prefixes not to pack (default: %(default)s)")
    ap.add_argument("--part-size-mib", type=int, default=1900)
    ap.add_argument("--level", type=int, default=12, help="zstd level")
    ap.add_argument("--ref", default="HEAD", help="commit the artifacts correspond to")
    ap.add_argument("--tag", help="release tag (default lake-cache-<short sha of --ref>)")
    ap.add_argument("--repo-slug", default="Rogerhu12/hecke-seven-eighths")
    ap.add_argument("--upload", action="store_true", help="create the GitHub release")
    args = ap.parse_args()

    repo = args.repo.resolve()
    sha = git(repo, "rev-parse", args.ref)
    tag = args.tag or f"lake-cache-{sha[:7]}"
    roots, stale = stale_modules(repo, sha)
    stale = {m for m in stale if not excluded(m, args.exclude)}
    if stale:
        print(f"skipping {len(stale)} module(s) whose sources differ from {sha[:7]} "
              f"(changed: {', '.join(roots)})")
    files, stats = collect(repo, args.exclude, stale)
    total = sum(s["bytes"] for s in stats.values())
    print(f"{len(files)} files, {total / 2**30:.2f} GiB uncompressed")
    for root, s in stats.items():
        print(f"  {root}: {s['modules']} modules, {s['files']} files, {s['bytes'] / 2**30:.2f} GiB")

    t0 = time.time()
    parts = pack(repo, files, args.out, args.part_size_mib << 20, args.level)
    packed = sum(p["bytes"] for p in parts)
    print(f"{len(parts)} parts, {packed / 2**30:.2f} GiB compressed, {time.time() - t0:.0f}s")

    manifest = {
        "tag": tag,
        "commit": sha,
        "lean_toolchain": (repo / "lean-toolchain").read_text().strip(),
        "excluded_module_prefixes": args.exclude,
        "skipped_stale_modules": sorted(stale),
        "build_roots": stats,
        "uncompressed_bytes": total,
        "parts": parts,
        "created": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }
    (args.out / "lake-cache-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    with open(args.out / "SHA256SUMS", "w", newline="\n") as fh:
        for p in parts:
            fh.write(f"{p['sha256']}  {p['name']}\n")

    if args.upload:
        notes = (
            f"Precompiled Lake artifacts for commit {sha} "
            f"({stats['.lake/build']['modules']} project modules, excluding "
            f"{', '.join(args.exclude)}; plus class-field-theory and TauCeti).\n\n"
            "Restore with `.github/actions/restore-lake-cache` after `lake exe cache get`.\n"
            "Regenerate with `scripts/build_lake_cache.py --upload`."
        )
        assets = [str(args.out / p["name"]) for p in parts]
        assets += [str(args.out / "lake-cache-manifest.json"), str(args.out / "SHA256SUMS")]
        # Created as a draft: the restore action ignores drafts, so branches keep
        # using the previous cache until this one is verified and published with
        #   gh release edit <tag> --draft=false
        subprocess.run(
            ["gh", "release", "create", tag, "-R", args.repo_slug, "--draft",
             "--latest=false", "--target", sha, "--title", tag, "--notes", notes, *assets],
            check=True,
        )
        print(f"created draft release {tag}; publish it after the lake-cache-test workflow passes")


if __name__ == "__main__":
    sys.exit(main())
